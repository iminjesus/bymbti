/* 유형 → 이 질문에서의 확정 답. 선택지가 없어도 하나는 찍는다. */
function commitFor(type, sceneId) {
  const pool = COMMIT_POOLS[sceneId] || COMMIT_POOLS.daily;
  const i = PICK_ORDER.indexOf(type.code);
  const raw = pool[i] || pool[pool.length - 1];
  const parts = raw.split(' — ');
  return { answer: parts[0], why: parts[1] || '' };
}

